const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { Math, Infinity };
vm.createContext(context);
vm.runInContext(fs.readFileSync(__dirname + '/controller.js', 'utf8'), context);
const bot = context.controller;
const fp = 65536;
const hello = { side: 0, map: { width: 8, height: 8, terrain: Array(64).fill(0) }, draft: { costs: { apc: 3, mbt: 4, scout: 2 }, budget: 12, roster: ['apc','mbt','scout'] }, objectives: [{x:2*fp,y:2*fp,radius:fp,weight:3},{x:6*fp,y:6*fp,radius:fp,weight:1}] };
assert.deepEqual(Array.from(bot.draft(hello)), ['apc','mbt','scout','scout']);
bot.hello(hello);
const base={tick:41,side:0,canMove:true,contacts:[],objectives:hello.objectives,units:[{id:1,alive:true,kind:'apc',x:2*fp,y:2*fp,heading:0,reload:0}]};
let order=bot.tick(base).units[0];
assert.equal(order.throttle,0,'APC should hold its assigned capture point');
base.contacts=[{id:99,x:3*fp,y:2*fp}];
order=bot.tick(base).units[0];
assert.deepEqual(Array.from(order.aimAt), [3*fp,2*fp]);
assert.deepEqual(Array.from(order.fire), [3*fp,2*fp]);
base.units.push({id:2,alive:false,kind:'scout',x:0,y:0,heading:0});
assert.equal(bot.tick(base).units.length,1,'dead units must not receive orders');
console.log('controller checks passed');
